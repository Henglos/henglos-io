"""Writes hio/_preload.py: the runtime's modules, leaves first.

A board imports a module's imports inside it, one C stack frame chain per
level — and from main.py, or the REPL's `from hio.tools.repl import exchange`,
the runtime's imports went 15 levels deep (down to henglosio.sdk). The ESP8266
has about 8 KB of C stack: "maximum recursion depth exceeded". hio's
__init__ imports this list in order first, so each module finds what it
imports already loaded: a few levels at most.

    python scripts/preload.py           # rewrites the list
    python scripts/preload.py --check   # fails if it's out of date (a test runs it)

The list is every module the runtime imports at the top level, from what a
board starts (HIOSystem and what main.py and hio.tools use) — run it after
adding a module or an import.
"""

import ast
import os
import sys

HERE = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SOURCES = [HERE, os.path.join(HERE, "..", "hio-sdk", "src")]
OUTPUT = os.path.join(HERE, "hio", "_preload.py")

# What main.py imports — and so every board, at boot. hio.tools (the REPL's)
# imports only a few more (MemoryTransport), one level down once these are in:
# not preloaded, they'd take the heap on a board that never opens a REPL.
ENTRIES = [
	"hio.system.HIOSystem",
	"hio.system.SystemConfig",
	"hio.system.core.memory",
]

# MicroPython's own packages the runtime uses, nested too (asyncio > core >
# time): first of all.
STDLIB_FIRST = ["asyncio"]

# Imported before everything here — the package that preloads, and the list
# itself: not in it.
LOADED_FIRST = {"hio", "hio._preload", "henglosio"}


def find(module):
	for root in SOURCES:
		base = os.path.join(root, *module.split("."))
		if os.path.isfile(base + ".py"):
			return base + ".py"
		if os.path.isfile(os.path.join(base, "__init__.py")):
			return os.path.join(base, "__init__.py")
	return None


def top_level_imports(module):
	"""The runtime's modules `module` imports when it's imported — parents first."""
	path = find(module)
	if not path:
		return []
	with open(path, encoding="utf-8") as file:
		tree = ast.parse(file.read())
	package = module if path.endswith("__init__.py") else module.rpartition(".")[0]

	names = []
	for node in tree.body:
		statements = [node]
		if isinstance(node, ast.Try):
			statements = node.body + [stmt for handler in node.handlers for stmt in handler.body]
		for stmt in statements:
			if isinstance(stmt, ast.Import):
				names += [alias.name for alias in stmt.names]
			elif isinstance(stmt, ast.ImportFrom):
				base = stmt.module or ""
				if stmt.level:
					parts = package.split(".")
					if stmt.level > 1:
						parts = parts[:len(parts) - (stmt.level - 1)]
					base = ".".join(parts + ([base] if base else []))
				names.append(base)
				# `from package import module`
				names += [base + "." + alias.name for alias in stmt.names if find(base + "." + alias.name)]

	modules = []
	for name in names:
		parts = name.split(".")
		for i in range(1, len(parts) + 1):
			parent = ".".join(parts[:i])
			if find(parent) and parent not in modules:
				modules.append(parent)
	return modules


def preload_order():
	order, seen = [], set()

	def visit(module, stack):
		if module in seen or module in stack:
			return
		# Its packages first: importing it runs their __init__ — which may import
		# it and its siblings, each then one level down, not nested in another.
		parts = module.split(".")
		for i in range(1, len(parts)):
			visit(".".join(parts[:i]), stack | {module})
		for imported in top_level_imports(module):
			visit(imported, stack | {module})
		seen.add(module)
		order.append(module)

	for entry in ENTRIES:
		visit(entry, frozenset())
	return STDLIB_FIRST + [module for module in order if module not in LOADED_FIRST]


def render(order):
	lines = [
		"# Generated by scripts/preload.py — don't edit: run it after adding a module",
		"# or an import. The runtime's modules, leaves first: see hio/__init__.py.",
		"MODULES = (",
		*[f'\t"{module}",' for module in order],
		")",
		"",
	]
	return "\n".join(lines)


def main():
	content = render(preload_order())
	current = open(OUTPUT, encoding="utf-8").read() if os.path.exists(OUTPUT) else None
	if "--check" in sys.argv:
		if current != content:
			sys.exit("hio/_preload.py is out of date — run: python scripts/preload.py")
		return
	if current != content:
		with open(OUTPUT, "w", encoding="utf-8", newline="\n") as file:
			file.write(content)
	print(f"{len(preload_order())} modules in hio/_preload.py")


if __name__ == "__main__":
	main()
