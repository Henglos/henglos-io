def grid(art: str):
	rows = [row for row in art.strip("\n").split("\n")]
	assert len(rows) == 16, (len(rows))
	for row in rows:
		assert len(row) == 16, (row, len(row))
	return [[c == "#" for c in row] for row in rows]


def from_grid(cells):
	return "\n".join("".join("#" if c else "." for c in row) for row in cells)


icons = {name: grid(art) for name, art in ART.items()}
icons["arrow_down"] = icons["arrow_up"][::-1][1:] + [icons["arrow_up"][::-1][0]]
icons["arrow_right"] = [[icons["arrow_up"][15 - x][y] for x in range(16)] for y in range(16)]
icons["arrow_left"] = [row[::-1] for row in icons["arrow_right"]]

# The cross and the clock, drawn rather than typed.
icons["cross"] = [[(x == y or x == y + 1 or x + y == 15 or x + y == 14) and 2 <= y <= 13 and 1 <= x <= 14 for x in range(16)] for y in range(16)]
clock = [[False] * 16 for _ in range(16)]
for y in range(16):
	for x in range(16):
		d = ((x - 7.5) ** 2 + (y - 7.5) ** 2) ** 0.5
		clock[y][x] = 6.3 <= d <= 7.6
for y in range(3, 8):
	clock[y][7] = True
for x in range(8, 12):
	clock[7][x] = True
icons["clock"] = clock


def hlsb(cells) -> bytes:
	out = bytearray()
	for row in cells:
		for half in (row[:8], row[8:]):
			value = 0
			for bit, on in enumerate(half):
				if on:
					value |= 0x80 >> bit
			out.append(value)
	return bytes(out)


